"""v0.3 freeze registry (spec v0.3 §14 V0c, §15): ``experiments/registry_v0_3.yaml``.

``compute_freeze(root)`` hashes every file that defines the v0.3 authoring
protocol (:data:`FROZEN_FILES`) and rebuilds the authoring packet in a
temporary directory to record its hash (sha256 of ``PACKET_MANIFEST.json``).
``write_registry`` writes the record (refusing to replace a different one
unless ``overwrite=True``); ``check_registry`` lists every mismatch.

Record keys: ``spec_version`` ("0.3"), ``files`` {path: sha256},
``packet_sha256``, ``freeze_sha256`` (sha256 of the canonical JSON of the
record without that key).
"""

from __future__ import annotations

import hashlib
import json
import tempfile
from pathlib import Path
from typing import Any

import yaml

from .packet import PacketError, build_packet

__all__ = ["FROZEN_FILES", "REGISTRY_RELPATH", "RegistryError", "compute_freeze", "write_registry", "check_registry"]

SPEC_VERSION = "0.3"
REGISTRY_RELPATH = "experiments/registry_v0_3.yaml"
V03_SPEC = "agent_doom_loop_detector_spec_v0_3.md"
V02_SPEC = "agent_doom_loop_detector_spec_v0_2.md"
SOURCE_DIR = "src/agent_loop_lab/v03"
KIT = "experiments/v0_3/author_kit"

FROZEN_FILES: tuple[str, ...] = (
    V03_SPEC,
    V02_SPEC,
    "pyproject.toml",
    "uv.lock",
    f"{SOURCE_DIR}/model.py",
    f"{SOURCE_DIR}/tokenizer.py",
    f"{SOURCE_DIR}/renderer.py",
    f"{SOURCE_DIR}/rawop.py",
    f"{SOURCE_DIR}/artifact.py",
    f"{SOURCE_DIR}/guards.py",
    f"{SOURCE_DIR}/runner.py",
    f"{SOURCE_DIR}/source_rules.py",
    f"{SOURCE_DIR}/packet.py",
    f"{SOURCE_DIR}/kit.py",
    f"{SOURCE_DIR}/registry.py",
    "src/agent_loop_lab/guards.py",  # the v0.2 guard the v0.3 guard builds on
    f"{KIT}/settings_v03_phase_a.json",
    f"{KIT}/settings_v03_phase_b.json",
    f"{KIT}/py",
    f"{KIT}/launch.py",
    f"{KIT}/prompt_v03_phase_a.md",
    f"{KIT}/prompt_continue.md",
    f"{KIT}/prompt_resubmit.md",
    "scripts/v03_prepare_author_dir.sh",
    "scripts/v03_launch.sh",
    "scripts/v03_audit_session.py",
    "scripts/v03_cost.py",
    "scripts/v03_run_build.py",
    "scripts/v03_build_packet.py",
)
KEYS = frozenset({"spec_version", "files", "packet_sha256", "freeze_sha256"})
_HEADER = (
    "# Freeze registry (spec v0.3, V0c). Generated by scripts/v03_freeze.py.\n"
    "# Do not edit by hand. Any change to a listed file creates a new registered version.\n"
)


class RegistryError(RuntimeError):
    pass


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def freeze_digest(record: dict[str, Any]) -> str:
    body = {k: v for k, v in record.items() if k != "freeze_sha256"}
    return _sha256(json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8"))


def packet_hash(root: str | Path) -> str:
    base = Path(root)
    with tempfile.TemporaryDirectory(prefix="v03_packet_") as tmp:
        try:
            manifest = build_packet(base / V03_SPEC, base / V02_SPEC, base / SOURCE_DIR, Path(tmp) / "packet")
        except (PacketError, OSError, UnicodeDecodeError) as exc:
            raise RegistryError(f"authoring packet could not be built: {exc}") from exc
    return manifest["packet_sha256"]


def compute_freeze(root: str | Path = ".") -> dict[str, Any]:
    base = Path(root)
    missing = [rel for rel in FROZEN_FILES if not (base / rel).is_file()]
    if missing:
        raise RegistryError(f"frozen files missing under {base}: {missing}")
    data = {rel: (base / rel).read_bytes() for rel in FROZEN_FILES}
    crlf = [rel for rel, b in data.items() if b"\r" in b]
    if crlf:
        raise RegistryError(f"frozen files have CR line endings: {crlf}")
    record: dict[str, Any] = {
        "spec_version": SPEC_VERSION,
        "files": {rel: _sha256(b) for rel, b in data.items()},
        "packet_sha256": packet_hash(base),
    }
    record["freeze_sha256"] = freeze_digest(record)
    return record


def _render(record: dict[str, Any]) -> str:
    return _HEADER + yaml.safe_dump(record, sort_keys=True, default_flow_style=False)


def write_registry(root: str | Path = ".", *, overwrite: bool = False) -> Path:
    text = _render(compute_freeze(root))
    path = Path(root) / REGISTRY_RELPATH
    if path.exists() and not overwrite:
        if path.read_text(encoding="utf-8") == text:
            return path
        raise RegistryError(f"{path} exists and differs from the current freeze; pass overwrite=True to replace it")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return path


def check_registry(root: str | Path = ".") -> list[str]:
    base = Path(root)
    path = base / REGISTRY_RELPATH
    if not path.is_file():
        return [f"registry not found: {path}"]
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        return [f"registry unreadable: {exc}"]
    if not isinstance(data, dict):
        return ["registry is not a mapping"]
    problems: list[str] = []
    if set(data) != KEYS:
        problems.append(f"registry keys {sorted(map(str, data))} != {sorted(KEYS)}")
    files = data.get("files") if isinstance(data.get("files"), dict) else {}
    for rel in FROZEN_FILES:
        if rel not in files:
            problems.append(f"not in registry: {rel}")
        elif not (base / rel).is_file():
            problems.append(f"frozen file missing: {rel}")
        elif _sha256((base / rel).read_bytes()) != files[rel]:
            problems.append(f"frozen file modified: {rel}")
    for rel in sorted(set(files) - set(FROZEN_FILES)):
        problems.append(f"registry lists a file that is not frozen: {rel}")
    try:
        actual = packet_hash(base)
        if actual != data.get("packet_sha256"):
            problems.append(f"packet_sha256 differs (registry {data.get('packet_sha256')}, rebuilt {actual})")
    except RegistryError as exc:
        problems.append(str(exc))
    if data.get("freeze_sha256") != freeze_digest(data):
        problems.append("registry freeze_sha256 does not match its record")
    return problems
