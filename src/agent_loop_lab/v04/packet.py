def rawop_section() -> str:
    """v0.3's operation-record table (the renderer's input), verbatim from its AUTHOR_INSTRUCTIONS."""
    text = p3.AUTHOR_INSTRUCTIONS
    start = text.find("## Operation records (`RawOp` dicts, the renderer's input)\n")
    end = text.find("## Deliverables and pinned interfaces")
    if start < 0 or end < start:
        raise PacketError("v0.3 AUTHOR_INSTRUCTIONS no longer has its operation-record section")
    return text[start:end].rstrip("\n") + "\n"


