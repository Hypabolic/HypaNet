def recovery():
    out = []
    # rA1: transient http failure, two retries, success, then work
    s = Session("rA1")
    s.read("svc/deploy/push.py")
    s.http("POST", "registry.example.net", "/v1/images/{name}/push", False, "FAIL0", error_class="TimeoutError", error_location="svc/deploy/push.py")
    s.http("POST", "registry.example.net", "/v1/images/{name}/push", False, "RETRY", error_class="TimeoutError", error_location="svc/deploy/push.py")
    s.http("POST", "registry.example.net", "/v1/images/{name}/push", True, "RESOLVES")
    s.read("svc/deploy/manifest.yaml")
    s.set_file("svc/deploy/manifest.yaml", ftext("manifest"))
    s.edit("svc/deploy/manifest.yaml", variant(ftext("manifest"), 2), dp=0.2)
    s.tests("deploy", 6, 6, "PROGRESS", dp=0.2)
    s.read("svc/deploy/rollout.py")
    s.search("svc", "rollout_wait")
    out.append(s)
    # rA2: polls with backoff while a dependency recovers
    s = Session("rA2")
    s.build("api_server", True, "PROGRESS", dp=0.1)
    s.http("POST", "deploy.example.org", "/jobs", True, "PROGRESS", body={"env": "staging"})
    s.poll("staging_job", "pending", "FAIL0", backoff=1)
    s.poll("staging_job", "pending", "POLL", backoff=2)
    s.poll("staging_job", "pending", "POLL", backoff=4)
    s.poll("staging_job", "pending", "POLL", backoff=8)
    s.poll("staging_job", "ready", "RESOLVES", backoff=16)
    s.http("GET", "deploy.example.org", "/jobs/{id}/logs", True, "NEW_FACT")
    s.tests("smoke", 4, 4, "PROGRESS", dp=0.2)
    s.read("ops/smoke/checks.py")
    out.append(s)
    # rA3: diagnosed build failure, read the location, fix, build ok
    s = Session("rA3")
    s.set_file("cmd/tool/main.c", ftext("main"))
    s.edit("cmd/tool/main.c", variant(ftext("main"), 1), dp=0.1)
    s.build("tool", False, "FAIL0", error_class="CompileError", error_location="cmd/tool/main.c")
    s.read("cmd/tool/main.c", lines=(300, 360))
    s.edit("cmd/tool/main.c", variant(variant(ftext("main"), 1), 3), dp=0.1)
    s.build("tool", True, "RESOLVES")
    s.tests("tool", 14, 14, "PROGRESS", dp=0.2)
    s.read("cmd/tool/args.c")
    s.search("cmd", "parse_args")
    s.read("cmd/tool/util.c")
    s.read("cmd/tool/io.c")
    out.append(s)
    # rA4: failing tests diagnosed and fixed within policy
    s = Session("rA4")
    s.set_file("web/forms/validate.ts", ftext("validate"))
    s.tests("forms", 8, 10, "FAIL0", error_class="TypeError", error_location="web/forms/validate.ts")
    s.read("web/forms/validate.ts")
    s.edit("web/forms/validate.ts", variant(ftext("validate"), 2), dp=0.1)
    s.tests("forms", 9, 10, "RETRY", dp=0.1, error_class="TypeError", error_location="web/forms/validate.ts")
    s.edit("web/forms/validate.ts", variant(variant(ftext("validate"), 2), 4), dp=0.1)
    s.tests("forms", 10, 10, "RESOLVES", dp=0.2)
    s.build("web", True, "PROGRESS", dp=0.05, family="lint")
    s.read("web/forms/submit.ts")
    s.search("web", "onSubmit")
    s.read("web/forms/schema.ts")
    s.read("web/forms/index.ts")
    out.append(s)
    # rA5: invented names, one controlled retry of a flaky test, resolved
    s = Session("rA5")
    s.read("zork/frotz.qx")
    s.set_file("zork/frotz.qx", ftext("frotz"))
    s.edit("zork/frotz.qx", variant(ftext("frotz"), 4), dp=0.2)
    s.tests("beta", 16, 17, "FAIL0", error_class="FlakyTimeout", error_location="zork/frotz_test.qx", tests=["beta/spin_wobble"])
    s.tests("beta", 17, 17, "RESOLVES", tests=["beta/spin_wobble"])
    s.build("zeta_bale", True, "PROGRESS", dp=0.05)
    s.read("zork/gnusto.qx")
    out.append(s)
    return out


def stalled():
    out = []
    # sA1: the same failing test run over and over with nothing changed
    s = Session("sA1")
    s.read("src/db/pool.py")
    s.set_file("src/db/pool.py", ftext("pool"))
    s.edit("src/db/pool.py", variant(ftext("pool"), 2), dp=0.05)
