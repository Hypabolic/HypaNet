#!/usr/bin/env node
// Bundle the codex word lists the rule layer reads (slop/codex/lists/*.txt) into one ES module,
// rules/src/codex-lists.js, so the linter does no file reads at run time and the kit carries the lists with the rules.
//
//   node slop/rules/make_codex_lists.mjs           write rules/src/codex-lists.js
//   node slop/rules/make_codex_lists.mjs --check   exit 1 if the file on disk differs from what would be written
//
// Each list keeps its sections ("# --- L01 hype verbs (...) ---" headers) with the codex id that opens the header, its
// entries in file order, the licence line of its header and the sha256 of the source file. Entries are trimmed,
// except in llm_glyphs.txt, whose header says spaces are part of an entry (" – "). Which entries a rule uses, and
// which it leaves out and why, is decided in the rule's own module, not here.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SLOP = path.join(HERE, '..');
const LISTS = path.join(SLOP, 'codex', 'lists');
export const OUT = path.join(HERE, 'src', 'codex-lists.js');

// The lists the rules read. llm_excess_vocab.txt (CC BY-SA 4.0) is deliberately not bundled: no rule uses it, and the
// rule layer's files stay MIT.
export const FILES = [
  'llm_promo_vocab.txt',
  'llm_constructions.txt',
  'llm_cta_cliches.txt',
  'llm_claims.txt',
  'llm_residue.txt',
  'llm_glyphs.txt',
  'ui_tech_pleonasms.txt',
];
const KEEP_SPACES = new Set(['llm_glyphs.txt']);

function parse(name, text) {
  const lines = text.split(/\r?\n/);
  const sections = [];
  let cur = null;
  let licence = null;
  let inHeader = true;
  let only = null; // a list without section headers names its one codex pattern in the header ("Codex pattern: U51.")
  for (const raw of lines) {
    if (raw.startsWith('#')) {
      const m = raw.match(/^# --- (.*)$/);
      if (m) {
        inHeader = false;
        const head = m[1].replace(/\s*---\s*$/, '');
        const id = (head.match(/^([LU]\d\d(?:\/[LU]\d\d)*|Block [A-Z])/) || [null, ''])[1];
        if (!id) throw new Error(`${name}: section header without a codex id: ${raw}`);
        const title = head.slice(id.length).replace(/\s*\(.*$/, '').replace(/^[:\s]+/, '').trim();
        cur = { id, title, entries: [] };
        sections.push(cur);
      } else if (inHeader) {
        const l = raw.match(/Licence:\s*(.+)$/);
        if (l && !licence) licence = l[1].trim();
        const p = raw.match(/\b[Pp]atterns?:\s*([LU]\d\d)\b/);
        if (p) only = p[1];
      }
      continue;
    }
    const entry = KEEP_SPACES.has(name) ? raw.replace(/\s+$/, (s) => (/^ +$/.test(s) ? s : '')) : raw.trim();
    if (!entry.trim()) continue;
    if (!cur && only) { cur = { id: only, title: '', entries: [] }; sections.push(cur); inHeader = false; }
    if (!cur) throw new Error(`${name}: entry before the first section header: ${raw}`);
    cur.entries.push(entry);
  }
  if (!licence) throw new Error(`${name}: no "Licence:" line in the header`);
  return { licence, sections };
}

export function buildCodexLists() {
  const parts = [];
  for (const name of FILES) {
    const buf = readFileSync(path.join(LISTS, name));
    const sha = createHash('sha256').update(buf).digest('hex');
    const { licence, sections } = parse(name, buf.toString('utf8'));
    const secs = sections.map((s) => `      { id: ${JSON.stringify(s.id)}, title: ${JSON.stringify(s.title)}, entries: [\n${s.entries.map((e) => `        ${JSON.stringify(e)},`).join('\n')}\n      ] },`);
    parts.push(`  ${JSON.stringify(name.replace(/\.txt$/, ''))}: {\n    file: ${JSON.stringify(`codex/lists/${name}`)},\n    sha256: ${JSON.stringify(sha)},\n    licence: ${JSON.stringify(licence)},\n    sections: [\n${secs.join('\n')}\n    ],\n  },`);
  }
  return `// GENERATED by rules/make_codex_lists.mjs from slop/codex/lists/*.txt. Do not edit: edit the lists, then run
//   node rules/make_codex_lists.mjs
// Sources, licences and attribution: slop/codex/SOURCES.md and slop/codex/lists/ATTRIBUTION-ui.md (ui_tech_pleonasms.txt
// shares nine entries with proselint, BSD-3-Clause; its notice is kept there). Every list here is MIT.

export const CODEX_LISTS = {
${parts.join('\n')}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildCodexLists();
  let old = null;
  try { old = readFileSync(OUT, 'utf8'); } catch { /* new file */ }
  if (process.argv.includes('--check')) {
    if (old !== text) { process.stderr.write(`stale: ${path.relative(SLOP, OUT)}\n`); process.exit(1); }
    process.exit(0);
  }
  if (old !== text) writeFileSync(OUT, text);
  process.stdout.write(`${path.relative(SLOP, OUT)}: ${FILES.length} lists${old === text ? ' (unchanged)' : ' written'}\n`);
}
