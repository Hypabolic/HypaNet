def leaky_imports(name: str, source: str) -> list[str]:
    """Imports in a packet ``.py`` of a harness, Qwen-side, kernel or dataset package (by module root)."""
    problems = []
    if p3._LEAKY_IMPORT_RE.search(source):
        problems.append(f"{name}: imports from the harness, generator or dataset packages")
    try:
        tree = ast.parse(source, filename=name)
    except SyntaxError as exc:
        return problems + [f"{name}: does not parse ({exc.msg})"]
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots = {a.name.split(".")[0] for a in node.names}
        elif isinstance(node, ast.ImportFrom) and not node.level:
            roots = {(node.module or "").split(".")[0]}
        else:
            continue
        bad = sorted(roots & LEAKY_IMPORT_ROOTS)
        if bad:
            problems.append(f"{name}: imports {bad}")
    return problems


def leakage_problems(texts: Mapping[str, str]) -> list[str]:
    """Every leakage check on packet text files (``texts``: name -> text; Qwen files must not be passed)."""
    problems = p3.leakage_problems({n: t for n, t in texts.items() if n in TEXT_FILES})
    for name, text in sorted(texts.items()):
        if name.endswith(".md") or name == MANIFEST_FILE:
            for s in V04_SENTINELS:
                if s in text:
                    problems.append(f"{name}: contains withheld v0.4 text {s!r}")
            for rx in _SPLIT_RES:
                hits = sorted(set(rx.findall(text)))
                if hits:
                    problems.append(f"{name}: names a data split or sealed set {hits}")
        if name.endswith(".py"):
            problems += leaky_imports(name, text)
    return problems


# -- build / verify -------------------------------------------------------------------------


def _entries(root: Path) -> list[str]:
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*"))


def _qwen_bytes(snapshot: Path, pins: Mapping[str, Any]) -> dict[str, bytes]:
    out = {}
    for name in QWEN_FILES:
        p = snapshot / name
        if not p.is_file():
            raise PacketError(f"Qwen snapshot file missing: {name} (snapshot {pins['model_id']}@{pins['revision']})")
        data = p.read_bytes()
        if _sha256(data) != pins["file_sha256"][name]:
            raise PacketError(f"qwen/{name}: sha256 {_sha256(data)} != pinned {pins['file_sha256'][name]}")
        out[f"{QWEN_DIR}/{name}"] = data
    return out


def build_packet(v04_spec: str | Path, v02_spec: str | Path, source_dir: str | Path, out_dir: str | Path, *,
                 qwen_snapshot: str | Path | None = None, interface_path: str | Path = DEFAULT_INTERFACE,
                 model_py: str | Path = DEFAULT_MODEL_PY, qwen_init: str | Path = DEFAULT_QWEN_INIT) -> dict[str, Any]:
    """Build the packet into ``out_dir`` (absent, empty or a previous packet) and return the manifest."""
    v04_spec, v02_spec, src, out = Path(v04_spec), Path(v02_spec), Path(source_dir), Path(out_dir)
    missing = [n for n in PACKET_SOURCE_FILES if not (src / n).is_file()]
    if missing:
        raise PacketError(f"packet sources missing from {src}: {missing}")
    if out.exists():
        if not out.is_dir():
            raise PacketError(f"{out} exists and is not a directory")
        stray = [e for e in _entries(out) if e not in PACKET_ENTRIES]
        if stray:
            raise PacketError(f"{out} contains entries that are not packet files: {stray}")
    pins = qwen_pins(Path(model_py), Path(qwen_init))
    snapshot = Path(qwen_snapshot) if qwen_snapshot else qwen_snapshot_dir(pins["model_id"], pins["revision"])
    qwen = _qwen_bytes(snapshot, pins)
    iface = load_interface(Path(interface_path))
    raw = {n: (src / n).read_bytes() for n in PACKET_SOURCE_FILES}
    spec4, spec2 = v04_spec.read_bytes(), v02_spec.read_bytes()
    for label, data in [("v0.4 spec", spec4), ("v0.2 spec", spec2), *raw.items()]:
        if b"\r" in data:
            raise PacketError(f"{label} has CR line endings; packet sources must be LF")
    for name, data in raw.items():
        bad = leaky_imports(name, data.decode("utf-8"))
        if bad:
            raise PacketError("; ".join(bad))
    tok = p3._load_module("_v04_packet_build_tokenizer", src / "tokenizer.py")
    grammar = p3.grammar_sheet(tok).encode("utf-8")
    if _sha256(grammar) != GRAMMAR_SHEET_SHA256:
        raise PacketError(f"{GRAMMAR_FILE}: regenerated sha256 {_sha256(grammar)} != the v0.3 author's copy")
    contents: dict[str, bytes] = {
        SPEC_FILE: extract_packet_spec(spec4.decode("utf-8"), spec2.decode("utf-8")).encode("utf-8"),
        INSTRUCTIONS_FILE: AUTHOR_INSTRUCTIONS.encode("utf-8"),
        INTERFACE_FILE: interface_md(iface, qwen[f"{QWEN_DIR}/tokenizer.json"]).encode("utf-8"),
        GRAMMAR_FILE: grammar,
        **raw,
        **qwen,
    }
    assert tuple(contents) == CONTENT_FILES
    manifest = {
        "packet_format_version": PACKET_FORMAT_VERSION,
        "spec_version": SPEC_VERSION,
        "files": {n: _sha256(d) for n, d in sorted(contents.items())},
        "sources": {
            "spec_v0_4": _sha256(spec4),
            "spec_v0_2": _sha256(spec2),
            **{f"v03/{n}": _sha256(d) for n, d in sorted(raw.items())},
        },
        "interface": {"name": iface.FROZEN.name, "spec_sha256": iface.spec_sha256(), "label_ids": list(LABEL_IDS),
                      "prefix_tokens": len(PREFIX_IDS), "suffix_tokens": len(SUFFIX_IDS)},
        "qwen": {"model_id": pins["model_id"], "revision": pins["revision"],
                 "files": {n: pins["file_sha256"][n] for n in QWEN_FILES}},
        "spec_sections": "v0.4 [packet] sections; v0.2 " + ", ".join(p3.V02_SECTIONS),
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / QWEN_DIR).mkdir(exist_ok=True)
    for name, data in contents.items():
        (out / name).write_bytes(data)
    (out / MANIFEST_FILE).write_bytes(_pretty_json(manifest))
    problems = verify_packet(out, interface_path=interface_path, model_py=model_py, qwen_init=qwen_init)
    if problems:
        raise PacketError("built packet failed verification: " + "; ".join(problems))
    return {**manifest, "packet_sha256": packet_sha256(out)}


def verify_packet(packet_dir: str | Path, *, interface_path: str | Path = DEFAULT_INTERFACE,
                  model_py: str | Path = DEFAULT_MODEL_PY, qwen_init: str | Path = DEFAULT_QWEN_INIT) -> list[str]:
    """Problems with the packet in ``packet_dir``; ``[]`` means OK."""
    out = Path(packet_dir)
    if not out.is_dir():
        return [f"packet directory not found: {out}"]
    problems: list[str] = []
    entries = _entries(out)
    for e in entries:
        if e not in PACKET_ENTRIES:
            problems.append(f"stray entry: {e}")
        if p3._is_leaky(e):
            problems.append(f"entry from a generator/dataset/oracle/review path: {e}")
        if (out / e).is_symlink():
            problems.append(f"symlink: {e}")
    for name in PACKET_FILES:
        if name not in entries:
            problems.append(f"missing file: {name}")
    if problems:
        return problems
    try:
        manifest_text = (out / MANIFEST_FILE).read_bytes().decode("utf-8")
        manifest = json.loads(manifest_text)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        return [f"{MANIFEST_FILE}: unreadable ({exc})"]
    files = manifest.get("files") if isinstance(manifest, dict) else None
    if not isinstance(files, dict) or sorted(files) != sorted(CONTENT_FILES):
        return [f"{MANIFEST_FILE}: file list differs from {sorted(CONTENT_FILES)}"]
    for name in CONTENT_FILES:
        data = (out / name).read_bytes()
        if _sha256(data) != files[name]:
            problems.append(f"hash mismatch: {name}")
        if name in TEXT_FILES and b"\r" in data:
            problems.append(f"{name}: CR line endings")
    for name in PACKET_SOURCE_FILES:
        if manifest.get("sources", {}).get(f"v03/{name}") != files[name]:
            problems.append(f"{name}: not a verbatim copy of its recorded source")
    try:
        pins = qwen_pins(Path(model_py), Path(qwen_init))
    except (OSError, PacketError) as exc:
        return problems + [f"Qwen pins unreadable: {exc}"]
    for name in QWEN_FILES:
        if files[f"{QWEN_DIR}/{name}"] != pins["file_sha256"][name]:
            problems.append(f"{QWEN_DIR}/{name}: sha256 differs from the pinned checkpoint file")
    if manifest.get("qwen", {}).get("revision") != pins["revision"]:
        problems.append(f"{MANIFEST_FILE}: Qwen revision differs from the pin")
    if manifest.get("interface", {}).get("spec_sha256") != INTERFACE_SPEC_SHA256:
        problems.append(f"{MANIFEST_FILE}: interface spec_sha256 differs from the frozen interface")
    texts = {n: (out / n).read_text(encoding="utf-8") for n in TEXT_FILES}
    problems += leakage_problems({**texts, MANIFEST_FILE: manifest_text})
    if p3.MARKER in texts[SPEC_FILE]:
        problems.append(f"{SPEC_FILE}: still contains the {p3.MARKER} marker")
    if texts[INSTRUCTIONS_FILE] != AUTHOR_INSTRUCTIONS:
        problems.append(f"{INSTRUCTIONS_FILE}: does not match the builder's text")
    if problems:
        return problems
    try:
        tok = p3._load_module("_v04_packet_verify_tokenizer", out / "tokenizer.py")
        if texts[GRAMMAR_FILE] != p3.grammar_sheet(tok) or files[GRAMMAR_FILE] != GRAMMAR_SHEET_SHA256:
            problems.append(f"{GRAMMAR_FILE}: does not match the packet tokenizer's output or the v0.3 author's copy")
        iface = load_interface(Path(interface_path))
        if texts[INTERFACE_FILE] != interface_md(iface, (out / QWEN_DIR / "tokenizer.json").read_bytes()):
            problems.append(f"{INTERFACE_FILE}: does not match the interface definition")
    except Exception as exc:  # noqa: BLE001 - a broken packet module or interface is a packet problem
        problems.append(f"packet modules could not be checked: {type(exc).__name__}: {exc}")
    return problems
