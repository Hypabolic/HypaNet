def extract_packet_spec(v04_text: str, v02_text: str) -> str:
    """``SPEC.md``: v0.3's extraction, with v0.4's preambles in place of v0.3's."""
    text = p3.extract_packet_spec(v04_text, v02_text)
    head = p3.SPEC_PREAMBLE.rstrip("\n")
    if not text.startswith(head) or text.count(p3.V02_PREAMBLE) != 1:
        raise PacketError("v0.3 spec extraction changed shape; cannot place the v0.4 preambles")
    return SPEC_PREAMBLE.rstrip("\n") + text[len(head):].replace(p3.V02_PREAMBLE, V02_PREAMBLE)


