"""Freeze registry for the M0 frozen files (spec v0.2 §2.2, §8, §14, §15).

``compute_freeze`` hashes the files that define the experiment (spec,
environment pins ``pyproject.toml`` and ``uv.lock``, oracle config and its
loader, schema, fingerprints, encoder, gate, model, packet builder, guard and
build runner) and builds the authoring packet into a temporary directory to
record its hash. ``write_registry`` records all of this in
``experiments/registry.yaml`` at M0 sign-off, and ``check_registry`` reports any
frozen file that has changed since, rebuilding the packet to confirm its hash
(spec §15 item 1).

Registry record (``REGISTRY_KEYS``)::

    spec_version               "0.2"
    files                      {frozen path: sha256 of raw bytes}
    packet_sha256              MANIFEST.json packet_sha256 of the rebuilt packet
    packet_source_spec_sha256  MANIFEST.json source_spec_sha256 (sha256 of the spec the packet was built from)
    freeze_sha256              sha256 of canonical JSON of the record minus freeze_sha256

The packet is built with the *imported* ``agent_loop_lab.packet`` (whose own
source is a frozen file) from ``<root>/agent_doom_loop_detector_spec_v0_2.md``
and ``<root>/src/agent_loop_lab/model.py``. The build is path-free and
deterministic, so the same sources always give the same ``packet_sha256``.

Hashes are of the raw file bytes, so they depend on line endings. The frozen
files must be LF (pinned by ``.gitattributes``): ``compute_freeze`` refuses a
file containing CR, and ``check_registry`` names CR line endings explicitly so a
CRLF checkout is not mistaken for a content change.
"""

from __future__ import annotations

import hashlib
import json
import tempfile
from pathlib import Path
from typing import Any, Mapping

import yaml

from .packet import PacketError, build_packet
from .schema import SPEC_VERSION

SPEC_RELPATH = "agent_doom_loop_detector_spec_v0_2.md"
MODEL_RELPATH = "src/agent_loop_lab/model.py"

FROZEN_FILES = (
    SPEC_RELPATH,
    "pyproject.toml",  # [R3] environment pins (torch, numpy, pyyaml, Python range)
    "uv.lock",  # [R3] exact resolved environment
    "oracle_config.v0_2.yaml",
    "src/agent_loop_lab/oracle_config.py",  # [R3] the oracle-config loader and validator
    "src/agent_loop_lab/schema.py",
    "src/agent_loop_lab/fingerprint.py",
    "src/agent_loop_lab/encode.py",
    "src/agent_loop_lab/windows.py",
    MODEL_RELPATH,
    "src/agent_loop_lab/packet.py",
    "src/agent_loop_lab/guards.py",
    "src/agent_loop_lab/runner.py",
)
PACKET_KEYS = ("packet_sha256", "packet_source_spec_sha256")
REGISTRY_RELPATH = "experiments/registry.yaml"
REGISTRY_KEYS = frozenset({"spec_version", "files", *PACKET_KEYS, "freeze_sha256"})

_HEADER = (
    "# Freeze registry (spec v0.2). Generated by scripts/freeze.py at M0 sign-off.\n"
    "# Do not edit by hand. Any change to a listed file creates a new registered spec version.\n"
)


class RegistryError(RuntimeError):
    """Raised when the registry (or the packet it records) cannot be computed or written."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical_json(obj: Any) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode("utf-8")


def freeze_digest(record: Mapping[str, Any]) -> str:
    """sha256 of canonical JSON of ``record`` without its ``freeze_sha256`` key.

    Canonical JSON: sorted keys at every level, no insignificant whitespace,
    UTF-8. Raises ``TypeError``/``ValueError`` if the record is not plain JSON data.
    """
    body = {k: v for k, v in record.items() if k != "freeze_sha256"}
    return _sha256(_canonical_json(body))


def packet_hashes(root: str | Path = ".") -> dict[str, str]:
    """Build the authoring packet from ``root``'s spec and model into a temporary directory.

    Returns ``{"packet_sha256": ..., "packet_source_spec_sha256": ...}`` from the
    built manifest. Raises ``RegistryError`` if the packet cannot be built or
    fails verification.
    """
    base = Path(root)
    with tempfile.TemporaryDirectory(prefix="agent_loop_lab_packet_") as tmp:
        try:
            manifest = build_packet(base / SPEC_RELPATH, base / MODEL_RELPATH, Path(tmp) / "packet")
        except (PacketError, OSError, UnicodeDecodeError) as exc:
            raise RegistryError(f"authoring packet could not be built: {exc}") from exc
    return {"packet_sha256": manifest["packet_sha256"], "packet_source_spec_sha256": manifest["source_spec_sha256"]}


def compute_freeze(root: str | Path = ".") -> dict[str, Any]:
    """The registry record (see the module docstring for its keys).

    Raises ``FileNotFoundError`` if a frozen file is missing and ``RegistryError``
    if one contains CR line endings or the authoring packet cannot be built.
    """
    base = Path(root)
    missing = [rel for rel in FROZEN_FILES if not (base / rel).is_file()]
    if missing:
        raise FileNotFoundError(f"frozen files missing under {base}: {missing}")
    data = {rel: (base / rel).read_bytes() for rel in FROZEN_FILES}
    crlf = [rel for rel, b in data.items() if b"\r" in b]
    if crlf:
        raise RegistryError(f"frozen files have CR line endings (freeze requires LF): {crlf}")
    record: dict[str, Any] = {
        "spec_version": SPEC_VERSION,
        "files": {rel: _sha256(b) for rel, b in data.items()},
        **packet_hashes(base),
    }
    record["freeze_sha256"] = freeze_digest(record)
    return record


def registry_path(root: str | Path = ".") -> Path:
    return Path(root) / REGISTRY_RELPATH


def _render(freeze: dict[str, Any]) -> str:
    return _HEADER + yaml.safe_dump(freeze, sort_keys=True, default_flow_style=False, allow_unicode=True)


def write_registry(root: str | Path = ".", *, overwrite: bool = False) -> Path:
    """Write ``experiments/registry.yaml`` and return its path.

    Rewriting an identical registry is a no-op. Replacing a registry whose
    content differs requires ``overwrite=True``, so a freeze can't be moved
    silently.
    """
    text = _render(compute_freeze(root))
    path = registry_path(root)
    if path.exists() and not overwrite:
        if path.read_text(encoding="utf-8") == text:
            return path
        raise RegistryError(f"{path} exists and differs from the current freeze; pass overwrite=True to replace it")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return path


def _check_packet(base: Path, data: Mapping[str, Any]) -> list[str]:
    """Rebuild the packet and compare it with the recorded packet hashes.

    Skipped when the spec or model is missing or has CR line endings: those are
    already reported per file, and the builder refuses CR sources.
    """
    for rel in (SPEC_RELPATH, MODEL_RELPATH):
        f = base / rel
        if not f.is_file() or b"\r" in f.read_bytes():
            return []
    try:
        actual = packet_hashes(base)
    except RegistryError as exc:
        return [str(exc)]
    problems = []
    for key in PACKET_KEYS:
        recorded = data.get(key)
        if recorded != actual[key]:
            problems.append(f"authoring packet {key} differs from the registry (registry {recorded}, rebuilt {actual[key]})")
    return problems


def check_registry(root: str | Path = ".") -> list[str]:
    """Mismatches between the frozen files (and rebuilt packet) under ``root`` and the registry; ``[]`` means OK.

    A missing or malformed registry is reported as a problem, not raised.
    """
    base = Path(root)
    path = registry_path(base)
    if not path.is_file():
        return [f"registry not found: {path}"]
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        return [f"registry unreadable: {exc}"]
    if not isinstance(data, dict):
        return ["registry is not a mapping"]
    problems: list[str] = []
    if set(data) != REGISTRY_KEYS:
        problems.append(f"registry keys {sorted(map(str, data))} != {sorted(REGISTRY_KEYS)}")
    if data.get("spec_version") != SPEC_VERSION:
        problems.append(f"registry spec_version {data.get('spec_version')!r} != {SPEC_VERSION!r}")
    for key in PACKET_KEYS:
        if not isinstance(data.get(key), str):
            problems.append(f"registry {key!r} must be a sha256 string")
    files = data.get("files")
    if not isinstance(files, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in files.items()):
        problems.append("registry 'files' must map path -> sha256 string")
        return problems
    for rel in FROZEN_FILES:
        if rel not in files:
            problems.append(f"not in registry: {rel}")
    for rel in sorted(set(files) - set(FROZEN_FILES)):
        problems.append(f"registry lists a file that is not frozen: {rel}")
    for rel in FROZEN_FILES:
        if rel not in files:
            continue
        f = base / rel
        if not f.is_file():
            problems.append(f"frozen file missing: {rel}")
            continue
        raw = f.read_bytes()
        actual = _sha256(raw)
        if actual != files[rel]:
            if b"\r" in raw and _sha256(raw.replace(b"\r\n", b"\n")) == files[rel]:
                problems.append(f"frozen file has CRLF line endings (content otherwise matches): {rel}")
            else:
                problems.append(f"frozen file modified: {rel} (registry {files[rel]}, now {actual})")
        elif b"\r" in raw:
            problems.append(f"frozen file contains CR line endings: {rel}")
    problems.extend(_check_packet(base, data))
    try:
        digest_ok = data.get("freeze_sha256") == freeze_digest(data)
    except (TypeError, ValueError):
        digest_ok = False
    if not digest_ok:
        problems.append("registry freeze_sha256 does not match its record")
    return problems
