"""F19 (post Figure 22): "Climbing, but counted as stuck", one typical OOD false alarm of the no-tools revision.

Run from the repo root:  uv run python scripts/blog/figures/f19.py

Reads the committed experiments/v0_5/ood_analysis/FINDINGS.md section 4(b): the eight-event example (log lines,
the network's rule tag per event, the labeller's latent effect per event) and its stated window facts (family,
progress delta, the labeller's ineffective count, v0.3 B's verdict). The window comes from the fresh OOD
diagnostic batch generated by analyse.py with master seed 20261107, not from the sealed set.

If the gitignored per-window rows (experiments/v0_5/ood_analysis/rows.jsonl.gz, regenerated by analyse.py on seed
20261107) are present, the example is cross-checked against window o-8193e459fdd00e1a at position 10: the same
write/run alternation, the same rule tags and labeller effects, 8 of 8 network-ineffective events, labeller
ineffective count 0, labeller PRODUCTIVE, v0.5 B STALLED, v0.3 B PRODUCTIVE. The rows carry no file names or
line numbers, so the log text itself comes from FINDINGS.md only. No sealed data, evaluator or scorer is opened.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "blog_figures" / "F19.json"
GENERATED_BY = "scripts/blog/figures/f19.py"

FINDINGS = ROOT / "experiments" / "v0_5" / "ood_analysis" / "FINDINGS.md"
ANALYSE = ROOT / "experiments" / "v0_5" / "ood_analysis" / "analyse.py"
ROWS = ROOT / "experiments" / "v0_5" / "ood_analysis" / "rows.jsonl.gz"  # gitignored; regenerated, seed 20261107
SOURCES = [FINDINGS, ANALYSE]
EXAMPLE = {"sid": "o-8193e459fdd00e1a", "pos": 10}
SEED = 20261107

EVENT = re.compile(
    r"^(?P<cmd>write_file (?P<file>\S+)\s+-> ok|run_tests -> FAILED (?P<passed>\d+)/(?P<total>\d+)\s+at (?P<loc>\S+))"
    r"\s+INEFF \((?P<rule>[A-Za-z_]+)\)\s+oracle (?P<effect>[A-Z]+)\s*$"
)


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT))


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def parse_findings() -> dict:
    text = FINDINGS.read_text()
    sec = text[text.index("**(b) Failure identity"):text.index("**(c)")]
    head = re.search(r"Typical OOD false alarm \(`(?P<family>[a-z_]+)`, Δp \+(?P<dp>[0-9.]+), oracle\s+I = (?P<I>\d+)\)", sec)
    block = sec[sec.index("```") + 3:]
    block = block[block.index("\n") + 1:block.index("```")]
    events = []
    for line in block.strip().splitlines():
        m = EVENT.match(line.strip())
        assert m, f"unparsed event line: {line!r}"
        if m.group("file"):
            events.append({"kind": "write", "tool": "write_file", "target": m.group("file"), "outcome": "ok",
                           "rule": m.group("rule"), "effect": m.group("effect")})
        else:
            file, line_no = m.group("loc").rsplit(":", 1)
            events.append({"kind": "run", "tool": "run_tests", "outcome": "FAILED", "passed": int(m.group("passed")),
                           "total": int(m.group("total")), "error_file": file, "error_line": int(line_no),
                           "rule": m.group("rule"), "effect": m.group("effect")})
    v03 = re.search(r"v0\.3 B sees ([0-9 →]+) as new highs and calls it ([A-Z]+)", sec)
    eight = re.search(r"That makes (\d+) of (\d+) events ineffective, so ([A-Z]+)", sec)
    return {
        "family": head.group("family"),
        "dp": float(head.group("dp")),
        "labeller_ineffective": int(head.group("I")),
        "events": events,
        "v03b_highs": [int(x) for x in v03.group(1).split("→")],
        "v03b_class": v03.group(2),
        "net_ineffective": [int(eight.group(1)), int(eight.group(2))],
        "v05b_class": eight.group(3),
        "seed_stated": f"master seed {SEED}" in text,
    }


def cross_check(f: dict) -> dict:
    """Compare the FINDINGS example with the regenerated row, when the gitignored rows file is present."""
    if not ROWS.exists():
        return {"ran": False, "reason": "rows.jsonl.gz not present; rerun analyse.py (seed 20261107) to cross-check"}
    with gzip.open(ROWS, "rt") as fh:
        row = next(r for r in map(json.loads, fh) if r["sid"] == EXAMPLE["sid"] and r["pos"] == EXAMPLE["pos"])
    kinds = ["write" if e["head"].startswith("write_file") else "run" for e in row["events"]]
    assert kinds == [e["kind"] for e in f["events"]]
    assert [e["parts"] for e in row["events"]] == [[e["rule"]] for e in f["events"]]
    assert [e["effect"] for e in row["events"]] == [e["effect"] for e in f["events"]]
    assert all(e["net_ineff"] and not e["oracle_red"] for e in row["events"])
    assert row["family"] == f["family"] and round(row["oracle"]["dp"], 2) == f["dp"] and row["oracle"]["I"] == 0
    assert row["net_I"] == 8 and row["label"] == "PRODUCTIVE" and row["v05b"] == "STALLED" and row["v03b"] == "PRODUCTIVE"
    per_write = sorted({e["dp"] for e in row["events"] if e["head"].startswith("write_file")})
    return {
        "ran": True,
        "rows_sha256": sha256(ROWS),
        "window": EXAMPLE,
        "matches": "structure, rule tags, labeller effects, counts and verdicts (rows hold no file names or line numbers)",
        "labeller_class": row["label"],
        "per_write_dp": per_write,
        "stalled_logit": row["logits"][2],
    }


def build() -> dict:
    f = parse_findings()
    check = cross_check(f)
    runs = [e for e in f["events"] if e["kind"] == "run"]

    obj = {
        "_provenance": {
            "source": [rel(p) for p in SOURCES],
            "sha256": {rel(p): sha256(p) for p in SOURCES},
            "source_commits": {rel(p): git("log", "-1", "--format=%h", "--", rel(p)) for p in SOURCES},
            "git_commit": git("rev-parse", "HEAD"),
            "generated_by": GENERATED_BY,
            "population": f"fresh OOD diagnostic batch (analyse.py, master seed {SEED}), not the sealed set",
            "cross_check": check,
        },
        "split": "fresh OOD batch",
        "seed": SEED,
        "family": f["family"],
        "events": f["events"],
        "rules": {
            "EDR": "a file change within 3 events after a repeated test result",
            "g_SAME": "a failure whose error line was seen in the last 15 events",
        },
        "verdicts": {
            "v05b": {"ineffective": f["net_ineffective"][0], "of": f["net_ineffective"][1], "class": f["v05b_class"]},
            "labeller": {"dp": f["dp"], "ineffective": f["labeller_ineffective"],
                         "class": check.get("labeller_class", "PRODUCTIVE")},
            "v03b": {"highs": f["v03b_highs"], "class": f["v03b_class"]},
        },
    }

    # The figure's claims, checked against the built data.
    assert f["seed_stated"]
    assert len(f["events"]) == 8 and [e["kind"] for e in f["events"]] == ["write", "run"] * 4
    assert [e["passed"] for e in runs] == [2, 3, 4, 5] == f["v03b_highs"] and {e["total"] for e in runs} == {14}
    assert {e["error_line"] for e in runs} == {354} and {e["error_file"] for e in runs} == {"contract_0.clj"}
    assert all(e["rule"] == "EDR" and e["effect"] == "PROGRESS" for e in f["events"] if e["kind"] == "write")
    assert all(e["rule"] == "g_SAME" and e["effect"] == "NONE" for e in runs)
    assert f["net_ineffective"] == [8, 8] and f["v05b_class"] == "STALLED" and f["v03b_class"] == "PRODUCTIVE"
    assert f["dp"] == 0.29 and f["labeller_ineffective"] == 0 and f["family"] == "shard_migration"
    return obj


def main() -> None:
    obj = build()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n")
    print(f"{OUT.relative_to(ROOT)} {OUT.stat().st_size:,} bytes; cross-check ran: {obj['_provenance']['cross_check']['ran']}")


if __name__ == "__main__":
    sys.exit(main())
